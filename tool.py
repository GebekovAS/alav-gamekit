def store(method, path, body=None, content_type="application/json"):
    """One request to the ALAV Store catalog with the developer key; returns the parsed JSON answer."""
    key = os.environ.get("ALAV_KEY", "").strip()
    if not key:
        sys.exit("publish needs a developer key: register at %s, create a key with the apps:publish scope "
                 "and set ALAV_KEY=<the key>" % DEVELOPERS)
    headers = {"X-Api-Key": key}
    if body is not None:
        headers["Content-Type"] = content_type
        if content_type == "application/json":
            body = json.dumps(body).encode("utf-8")
    url = os.environ.get("ALAV_STORE_URL", "https://alav.online").rstrip("/") + path
    try:
        with urllib.request.urlopen(urllib.request.Request(url, data=body, method=method, headers=headers),
                                    timeout=240) as response:
            text = response.read().decode("utf-8")
        return json.loads(text) if text.strip() else None
    except urllib.error.HTTPError as e:
        text = e.read().decode("utf-8", "replace").strip()
        try:
            err = json.loads(text)
            text = err.get("detail") or "; ".join(m for ms in err.get("errors", {}).values() for m in ms) \
                or err.get("title") or text
        except (ValueError, AttributeError, TypeError):
            pass
        hint = {401: " (is ALAV_KEY right and not revoked? keys: %s)" % DEVELOPERS,
                # the store answers 403 without a reason, so every cause is listed
                403: " (the key needs the apps:publish scope, and its developer account must be approved by the "
                     "store administrator and not blocked; the account state is shown on %s)" % DEVELOPERS}.get(e.code, "")
        sys.exit("the store refused: %s %s -> %d %s%s" % (method, path.split("?")[0], e.code, text[:500], hint))
    except (OSError, ValueError) as e:
        sys.exit("cannot reach the store at %s: %s" % (url.split("/api/")[0], e))


def store_upload(path, content_type):
    """Chunked upload of one file; returns its file id."""
    name, size = os.path.basename(path), os.path.getsize(path)
    total = max(1, -(-size // CHUNK))
    about = {"fileName": name, "fileSize": size, "totalChunks": total, "contentType": content_type, "isTemporary": False}
    upload_id = store("POST", "/api/v1/Files/upload/init", dict(about, chunkSize=CHUNK))["uploadId"]
    boundary = "alav" + os.urandom(12).hex()
    with open(path, "rb") as f:
        for index in range(total):
            chunk = f.read(CHUNK)
            fields = {"uploadId": upload_id, "chunkIndex": index, "totalChunks": total, "fileName": name,
                      "chunkSize": len(chunk), "isTemporary": "false"}
            body = b"".join(('--%s\r\nContent-Disposition: form-data; name="%s"\r\n\r\n%s\r\n' % (boundary, k, v))
                            .encode("utf-8") for k, v in fields.items())
            body += ('--%s\r\nContent-Disposition: form-data; name="chunk"; filename="%s"\r\nContent-Type: %s\r\n\r\n'
                     % (boundary, name, content_type)).encode("utf-8") + chunk + ("\r\n--%s--\r\n" % boundary).encode()
            store("POST", "/api/v1/Files/upload/chunk", body, "multipart/form-data; boundary=" + boundary)
    return store("POST", "/api/v1/Files/upload/complete", dict(about, uploadId=upload_id))["id"]


def cmd_publish(args):
    release = "--release" in args
    path = game_dir(next(a for a in args if not a.startswith("--")))
    slug = os.path.basename(path)
    info = meta(path)
    section, genres = GENRES.get(info.get("kind", "game"), ("", ()))
    if not section:
        sys.exit('game.json: "kind" must be "game" or "app"')
    if "genre" in info and info["genre"] not in genres:
        sys.exit('game.json: "genre" must be one of: ' + ", ".join(genres))
    problems = static_problems(path)
    if problems:
        sys.exit("not published, the game would not start on the console:\n - " + "\n - ".join(problems))
    icon = os.path.join(path, "icon.png")
    if not os.path.isfile(icon):
        sys.exit("not published: the store needs %s (PNG, at most 128x128 px and 64 KiB)" % relpath(icon))
    with open(icon, "rb") as f:
        head = f.read(24)  # the size of a PNG is in its IHDR header
    width, height = int.from_bytes(head[16:20], "big"), int.from_bytes(head[20:24], "big")
    if head[:8] != b"\x89PNG\r\n\x1a\n" or len(head) < 24:
        sys.exit("not published: icon.png is not a PNG file")
    if max(width, height) > 128 or os.path.getsize(icon) > 64 * 1024:
        sys.exit("not published: icon.png is %dx%d px, %d bytes; the store takes at most 128x128 px and "
                 "65536 bytes. Make it smaller" % (width, height, os.path.getsize(icon)))
    package_id = "ALAV." + slug
    version = info["version"]
    app, page = None, 1
    while not app:
        found = store("GET", "/api/v2/applications/mine?page=%d&pageSize=200" % page)
        app = next((a for a in found["applications"] if (a.get("packageId") or "").lower() == package_id.lower()), None)
        if page * 200 >= found["total"]:
            break
        page += 1
    old = next((v for v in app["versions"] if v["version"] == version), None) if app else None
    if old and old["status"] == 4:  # in review: its files are frozen until the administrator decides
        print("waiting for review: %s %s was already sent and is still waiting for approval; nothing is uploaded. "
              "It will appear in the ALAV Store after approval" % (info["title"], version))
        return 0
    if old and old["status"] != 0:
        sys.exit('version %s of %s is already published in the store: raise "version" in %s'
                 % (version, package_id, relpath(os.path.join(path, "game.json"))))
    rejected = (old or {}).get("rejectionReason")
    if rejected:
        print("the review rejected the earlier upload of %s: %s" % (version, rejected))
    if old and release and not rejected:
        print("draft %s is already uploaded: publishing it, nothing is uploaded again" % version)
        versions, ver = "/api/v2/applications/%s/versions" % app["id"], old
    else:
        zip_path = make_zip(path)[0]
        if not app:
            app = store("POST", "/api/v2/applications",
                        {"name": info["title"], "category": "ALAV Store " + section, "packageId": package_id})
            print("created %s in the store" % package_id)
        versions = "/api/v2/applications/%s/versions" % app["id"]
        if old:  # a draft of this version from an earlier run: replaced by the current build
            store("DELETE", "%s/%s" % (versions, old["id"]))
            print("removed the earlier draft %s" % version)
        store("PUT", "/api/v2/applications/" + app["id"],
              {"name": info["title"], "iconFileId": store_upload(icon, "image/png")})
        print("uploading %s (%d bytes) ..." % (os.path.basename(zip_path), os.path.getsize(zip_path)), flush=True)
        file_id = store_upload(zip_path, "application/zip")
        description = str(info.get("description") or info["title"])
        ver = store("POST", versions, {
            "version": version, "description": description[:500], "longDescription": description[:5000],
            "tags": ["ALAV Store", section] + ([info["genre"]] if "genre" in info else []),
            "fileId": file_id, "fileName": os.path.basename(zip_path), "fileSize": os.path.getsize(zip_path),
            "channel": "stable", "publishImmediately": False, "isMandatory": False, "rolloutPercent": 100})
        try:  # the store shows a version only with this artifact: a draft without it must not stay
            artifact = store("POST", "%s/%s/artifacts" % (versions, ver["id"]),
                             {"platform": "linux", "arch": "arm64", "format": "zip", "fileId": file_id})
            with open(zip_path, "rb") as f:
                local = (hashlib.sha256(f.read()).hexdigest(), os.path.getsize(zip_path))
            if (str(artifact["sha256"]).lower(), artifact["fileSize"]) != local:
                sys.exit("the store received a different file (size or SHA-256 differs)")
        except SystemExit as e:
            try:
                store("DELETE", "%s/%s" % (versions, ver["id"]))
            except SystemExit:
                pass
            sys.exit("%s\nnothing was published; run the command again" % e)
        print("uploaded %s %s" % (info["title"], version))
    if release:
        status = store("PATCH", "%s/%s/publish" % (versions, ver["id"]))["status"]
        if status == 4:  # every release of a developer is reviewed before it becomes public
            print("sent for review: %s %s will appear in the ALAV Store after the administrator approves it"
                  % (info["title"], version))
        elif status == 1:
            print("published: %s %s is in the ALAV Store, visible to everyone" % (info["title"], version))
        else:
            sys.exit("the store did not publish the version; look at it on " + DEVELOPERS)
    else:
        print("draft: %s %s is visible only to you. To publish it for everyone: python tool.py publish %s --release"
              % (info["title"], version, slug))
    return 0


def write_owned(path, text, pointer):
    """Write a generated file. A file somebody else wrote is kept: it only gets `pointer` appended once."""
    old = ""
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old and not old.startswith(MARK):
        if MARK in old:
            return print("  kept " + path)
        text = old.rstrip("\n") + "\n\n" + MARK + "\n" + pointer + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("  wrote " + path)


def cmd_setup(args):
    work = os.path.abspath(args[0] if args else os.path.dirname(ROOT))
    if work == ROOT:
        sys.exit("the kit folder is a workspace already: open it in your agent, nothing to set up")
    rel = relpath(ROOT, work).replace(os.sep, "/")
    tool = "python %s/tool.py" % rel
    os.makedirs(os.path.join(work, "games"), exist_ok=True)
    with open(os.path.join(ROOT, "AGENTS.md"), encoding="utf-8") as f:
        guide = f.read().split("\n", 1)[1]
    guide = guide[:guide.index("## If you were asked")] + guide[guide.index("## The 5 steps"):]  # that part is done
    rule = ("Any request here to make, build or test a game means: **a game for handheld consoles running ALAV Store, written "
            "in Python with the kit in `%s/`** - never an HTML, web, pygame or desktop game. " % rel)
    head = (MARK + "\n# This project makes games for handheld consoles running ALAV Store\n\n" + rule +
            "Follow the instructions below exactly.\n\n"
            "Folders: `games/<slug>/` - one folder per game, all your work goes here; `%(rel)s/` - the kit, "
            "read-only (its `examples/` are the templates); `out/` - check screenshots; `dist/` - packed games. "
            "Run every command from this folder, exactly as written: `%(tool)s ...`\n")
    guide = guide.replace("python tool.py", tool).replace("`examples/", "`%s/examples/" % rel)
    guide = guide.replace("Do not edit `kit/`, `tool.py` or `%s/examples/`. Your game lives in `games/<slug>/`." % rel,
                          "Do not edit anything inside `%s/`. Your game lives in `games/<slug>/`." % rel)
    print("workspace: " + work)
    pointer = rule + "Before writing any code read `%s/AGENTS.md` and follow it exactly; run its commands as `%s ...` from this folder; games live in `games/<slug>/`." % (rel, tool)
    write_owned(os.path.join(work, "AGENTS.md"), head % {"rel": rel, "tool": tool} + guide, pointer)
    write_owned(os.path.join(work, "CLAUDE.md"), MARK + "\n\n@AGENTS.md\n", pointer)
    skills = os.path.join(ROOT, ".claude", "skills")
    for name in sorted(os.listdir(skills)):
        with open(os.path.join(skills, name, "SKILL.md"), encoding="utf-8") as f:
            text = f.read().replace("python tool.py", tool).replace("`examples/", "`%s/examples/" % rel)
        target = os.path.join(work, ".claude", "skills", name, "SKILL.md")
        if not os.path.isfile(target) or "ALAV Store" in open(target, encoding="utf-8").read():
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    with open(os.path.join(ROOT, ".workspace"), "w", encoding="utf-8") as f:
        f.write(work)
    print("  games go to %s\nready. Start a NEW agent session in %s and ask for a game." % (os.path.join(work, "games"), work))


