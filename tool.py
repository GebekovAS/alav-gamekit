ROOT = os.path.dirname(os.path.abspath(__file__))
SLUG = r"[a-z0-9][a-z0-9_-]{0,39}"  # the store's rule for /storage/apps/<slug>; the lobby reports this name
KIT = os.path.join(ROOT, "kit")
MARK = "<!-- alav-gamekit workspace: generated by tool.py setup, re-run it after updating the kit -->"


def relpath(path, start=os.curdir):
    try:
        return os.path.relpath(path, start)
    except ValueError:  # Windows: the two are on different drives
        return os.path.abspath(path)


def workspace():
    """Where games/, out/ and dist/ live: the folder chosen by `setup`, else the kit itself."""
    try:
        with open(os.path.join(ROOT, ".workspace"), encoding="utf-8") as f:
            folder = f.read().strip()
        if os.path.isdir(folder):
            return folder
    except OSError:
        pass
    return ROOT


WORK = workspace()
DIST = os.path.join(WORK, "dist")
CHECK_FRAMES = 1800  # 30 seconds of play
# Measured: the console runs Python ~30x slower than a desktop PC (1M loop steps: 1.65 s vs 0.05 s).
MAX_PC_MS = 0.4      # average update+draw time per frame on the PC
MAX_DRAWS = 400      # draw calls in one frame
SKIP = ("__pycache__", "save.json", "save.json.tmp", "screenshot.png")


def game_dir(slug):
    for base in (os.path.join(WORK, "games"), os.path.join(ROOT, "games"), os.path.join(ROOT, "examples"), ""):
        path = os.path.abspath(os.path.join(base, slug))
        if os.path.isfile(os.path.join(path, "main.py")):
            if not re.fullmatch(SLUG, os.path.basename(path)):
                sys.exit("rename the folder %s: a game folder name is lowercase letters, digits, '-' or '_' "
                         "(at most 40), e.g. space-miner" % path)
            return path
    sys.exit("no game '%s': expected games/%s/main.py (create it: python tool.py new %s)" % (slug, slug, slug))


def meta(path):
    try:
        with open(os.path.join(path, "game.json"), encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        sys.exit("bad game.json in %s: %s" % (path, e))
    if not str(data.get("title", "")).strip() or not re.fullmatch(r"\d+\.\d+\.\d+", str(data.get("version", ""))):
        sys.exit('game.json needs "title" and "version" like "1.0.0"')
    return data


SDL_DIR = os.path.join(ROOT, ".sdl")


def ensure_sdl():
    """SDL2 for the PC, fetched from PyPI without pip (pip often cannot run inside an agent's sandbox)."""
    if os.path.isdir(SDL_DIR) or importlib.util.find_spec("sdl2dll"):
        return
    tag = {"win32": "win_amd64", "darwin": "macosx"}.get(sys.platform, "manylinux")
    try:
        with urllib.request.urlopen("https://pypi.org/pypi/pysdl2-dll/json", timeout=30) as r:
            files = [f for f in json.load(r)["urls"] if f["filename"].endswith(".whl") and tag in f["filename"]]
        if not files:
            return
        print("  downloading SDL2 (once) ...", flush=True)
        with urllib.request.urlopen(files[0]["url"], timeout=120) as r:
            wheel = r.read()
        if hashlib.sha256(wheel).hexdigest() != files[0]["digests"]["sha256"]:
            raise OSError("checksum mismatch")
        tmp = SDL_DIR + ".tmp"
        shutil.rmtree(tmp, ignore_errors=True)
        os.makedirs(tmp)
        with zipfile.ZipFile(io.BytesIO(wheel)) as z:
            for name in z.namelist():
                if name.startswith("sdl2dll/dll/") and not name.endswith("/"):
                    with open(os.path.join(tmp, os.path.basename(name)), "wb") as f:
                        f.write(z.read(name))
        os.replace(tmp, SDL_DIR)
    except (OSError, ValueError, KeyError, zipfile.BadZipFile) as e:
        print("  could not download SDL2 (%s). Install it by hand: python -m pip install pysdl2-dll" % e)


def play_env(**extra):
    ensure_sdl()
    env = dict(os.environ, PYTHONPATH=KIT, PYTHONDONTWRITEBYTECODE="1", PYTHONIOENCODING="utf-8")
    if os.path.isdir(SDL_DIR):
        env["ALAV_SDL_DIR"] = SDL_DIR
    env.update(extra)
    return env


# ------------------------------------------------------------------ new / run

def cmd_new(args):
    slug = args[0]
    if not re.fullmatch(r"[a-z][a-z0-9-]{1,30}", slug):
        sys.exit("slug must be lowercase letters, digits and '-', e.g. space-miner")
    src = game_dir(args[args.index("--from") + 1]) if "--from" in args else os.path.join(ROOT, "examples", "minimal")
    dst = os.path.join(WORK, "games", slug)
    if os.path.exists(dst):
        sys.exit(dst + " already exists")
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(*SKIP, ".*"))
    title = args[args.index("--title") + 1] if "--title" in args else slug.replace("-", " ").title()
    info = {"title": title, "version": "1.0.0"}
    if meta(src).get("net") is True:
        info["net"] = True
    with open(os.path.join(dst, "game.json"), "w", encoding="utf-8") as f:
        json.dump(info, f, ensure_ascii=False, indent=2)
    print("created %s\n"
          "  1. edit its main.py and game.json; rules and the whole API: AGENTS.md\n"
          "  2. check %s   -> repeat until PASS, then read the screenshots (.png or .txt)" % (relpath(dst), slug))


def cmd_run(args):
    path = game_dir(args[0])
    main = os.path.join(path, "main.py")
    if "--net" not in args:
        return subprocess.call([sys.executable, main], env=play_env())
    procs = [subprocess.Popen([sys.executable, main], env=play_env(ALAV_ROLE="host"))]
    time.sleep(1)
    procs.append(subprocess.Popen([sys.executable, main], env=play_env(ALAV_ROLE="join")))
    return max(p.wait() for p in procs)


