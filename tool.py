def static_problems(path):
    """Things that work on the PC but break on the console (Python 3.11, no pip packages)."""
    problems = []
    network = meta(path).get("net") is True
    local = {os.path.splitext(f)[0] for f in os.listdir(path)} | {"alav", "r36t"}
    for name in sorted(os.listdir(path)):
        if not name.endswith(".py"):
            continue
        file = os.path.join(path, name)
        with open(file, encoding="utf-8") as f:
            src = f.read()
        try:
            tree = ast.parse(src, name, feature_version=(3, 11))
            compile(src, name, "exec")
        except (SyntaxError, ValueError) as e:
            problems.append("%s: syntax error (the console has Python 3.11): %s" % (name, e))
            continue
        for node in ast.walk(tree):
            if (not network and isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and isinstance(node.func.value, ast.Name) and node.func.value.id in ("g", "alav", "r36t")
                    and node.func.attr in ("host", "join")):
                problems.append('%s:%d: network game: add "net": true to game.json so the store can host it'
                                % (name, node.lineno))
            mods = [a.name for a in node.names] if isinstance(node, ast.Import) else \
                [node.module or ""] if isinstance(node, ast.ImportFrom) and not node.level else []
            for mod in mods:
                top = mod.split(".")[0]
                if top not in sys.stdlib_module_names and top not in local:
                    problems.append("%s:%d: import %s - not available on the console; use only the "
                                    "standard library and alav" % (name, node.lineno, top))
        if sys.version_info >= (3, 12):  # f"{d["k"]}" is valid from 3.12 only
            open_quotes = []
            for tok in tokenize.generate_tokens(io.StringIO(src).readline):
                kind = tokenize.tok_name[tok.type]
                quote = tok.string.lstrip("rRbBfFuU")[:1]
                if kind in ("STRING", "FSTRING_START") and quote in open_quotes:
                    problems.append("%s:%d: the same quote character inside an f-string breaks on "
                                    "Python 3.11; use the other quote inside" % (name, tok.start[0]))
                if kind == "FSTRING_START":
                    open_quotes.append(quote)
                elif kind == "FSTRING_END":
                    open_quotes.pop()
    return problems


def headless(path, frames, tag="", **extra):
    shots = os.path.join(WORK, "out", "check", os.path.basename(path) + tag)
    shutil.rmtree(shots, ignore_errors=True)
    os.makedirs(shots)
    return shots, subprocess.Popen([sys.executable, os.path.join(path, "main.py")], stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace",
                                   env=play_env(ALAV_CHECK=str(frames), ALAV_SHOTS=shots, **extra))


def judge(name, proc, shots, net):
    problems = []
    try:
        out = proc.communicate(timeout=180)[0]
    except subprocess.TimeoutExpired:
        proc.kill()
        return ["%s: did not finish in 180 s - an endless loop inside update() or draw()?" % name], None
    found = re.search(r"^ALAV_CHECK (\{.*\})$", out, re.M)
    stats = json.loads(found.group(1)) if found else None
    if proc.returncode != 0 or not stats:
        tail = "\n".join(out.strip().splitlines()[-25:])
        return ["%s: the game crashed (exit code %s):\n%s" % (name, proc.returncode, tail)], None
    if stats["avg_ms"] > MAX_PC_MS and not net:
        problems.append("%s: too slow for the console: %.2f ms per frame here (limit %.1f). Do less work "
                        "per frame: fewer objects, no nested loops over all objects" % (name, stats["avg_ms"], MAX_PC_MS))
    if stats["draws"] > MAX_DRAWS:
        problems.append("%s: %d draw calls in one frame (limit %d). Draw only what is on screen; "
                        "use bigger tiles or fewer circles" % (name, stats["draws"], MAX_DRAWS))
    if stats["colors"] < 3:
        problems.append("%s: the screen is blank (one flat colour) - draw() shows nothing" % name)
    if net and not stats["net_peers"]:
        problems.append("%s: host and join never connected. Use g.ROLE to pick host/join without a menu "
                        "(see AGENTS.md, Network games)" % name)
    print("  %s: %d frames, %.2f ms/frame (worst %.1f), %d draw calls, screenshots: %s" % (
        name, stats["frames"], stats["avg_ms"], stats["max_ms"], stats["draws"], relpath(shots, WORK)))
    for txt in sorted(f for f in os.listdir(shots) if f.endswith(".txt")):
        with open(os.path.join(shots, txt), encoding="utf-8") as f:
            for line in f:
                if "PARTLY OFF SCREEN" in line:
                    print("  warning, %s: text does not fit on the screen: %s" % (txt, line.strip()))
    return problems, stats


def lobby_problems(slug):
    """Ask the running host what the store lobby asks; the answer must name this game."""
    data = b""
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
        s.settimeout(0.5)
        for _ in range(10):
            try:
                s.sendto(b"ALAV?*", ("127.0.0.1", 36036))
                data = s.recvfrom(512)[0]
                break
            except OSError:
                time.sleep(0.3)
    try:
        info = json.loads(data[6:].decode("utf-8"))
        ok = (data[:6] == b"ALAV!*" and len(data) <= 250 and info["slug"] == slug and isinstance(info["name"], str)
              and 0 < len(info["name"]) <= 40 and type(info["players"]) is int and info["players"] >= 1
              and ("max" not in info or type(info["max"]) is int and info["players"] <= info["max"] <= 99))
    except (ValueError, KeyError, TypeError):
        ok = False
    if ok:
        print("  lobby: %s" % data[6:].decode("utf-8"))
        return []
    return ["host: no valid answer to the store lobby probe (got %r). Host with g.host(NAME) and call "
            "net.recv() every frame (see AGENTS.md, Network games)" % data[:60]]


def cmd_check(args):
    path = game_dir(args[0])
    network = meta(path).get("net") is True or "--net" in args
    problems = static_problems(path)
    if not problems:
        if network:
            runs = [("host", *headless(path, 480, "-host", ALAV_ROLE="host", ALAV_PACE="1", ALAV_JOIN=""))]
            time.sleep(1)
            runs.append(("join", *headless(path, 420, "-join", ALAV_ROLE="join", ALAV_PACE="1", ALAV_JOIN="")))
            # started the way the store lobby does it: no role, only the host address
            runs.append(("lobby join", *headless(path, 420, "-lobby", ALAV_ROLE="", ALAV_PACE="1", ALAV_JOIN="127.0.0.1")))
            problems += lobby_problems(os.path.basename(path))
        else:
            runs = [("game", *headless(path, CHECK_FRAMES))]
        for name, shots, proc in runs:
            problems += judge(name, proc, shots, network)[0]
    if not os.path.isfile(os.path.join(path, "icon.png")):
        print("  note: no icon.png yet (needed only for publishing in the ALAV Store)")
    if problems:
        print("FAIL")
        for p in problems:
            print(" - " + p)
        return 1
    print("PASS - now look at the screenshots above (each .png has a .txt twin: the same screen as text, "
          "for models that cannot view images) and make sure the game looks right")
    return 0


# ------------------------------------------------------------------ pack / deploy

def stage(slug):
    """dist/<slug>/: the game plus the kit, exactly what ends up in /storage/apps/<slug>."""
    path = game_dir(slug)
    info = meta(path)
    out = os.path.join(DIST, os.path.basename(path))
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(path, out, ignore=shutil.ignore_patterns(*SKIP, ".*", "*.pyc", "test_*"))
    for name in ("alav.py", "r36t.py", "font.ttf", "font-license.txt"):  # r36t.py: old import name
        shutil.copy(os.path.join(KIT, name), out)
    with open(os.path.join(out, "version.txt"), "w", newline="\n") as f:
        f.write(info["version"] + "\n")
    return out, info


def tar_bytes(folder):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        tar.add(folder, arcname=".")
    return buf.getvalue()


