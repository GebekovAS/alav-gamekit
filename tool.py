def make_zip(slug):
    folder, info = stage(slug)
    slug = os.path.basename(folder)
    zip_path = os.path.join(DIST, "ALAV-%s-%s-linux-arm64.zip" % (slug, info["version"]))
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:  # main.py in the root: ALAV Store format
        for base, _, files in os.walk(folder):
            for name in sorted(files):
                full = os.path.join(base, name)
                z.write(full, os.path.relpath(full, folder).replace(os.sep, "/"))
    return zip_path, folder, info


def cmd_pack(args):
    zip_path, folder, info = make_zip(args[0])
    slug = os.path.basename(folder)
    sh_path = os.path.join(DIST, re.sub(r'[\\/:*?"<>|]', "", info["title"]).strip() + ".sh")
    head = INSTALLER % {"title": info["title"], "version": info["version"], "slug": slug}
    with open(sh_path, "wb") as f:
        f.write(head.encode() + base64.b64encode(tar_bytes(folder)) + b"\n")
    print("%s\n%s\n  -> copy the .sh to ports_scripts on the SD card and start it from Ports" % (zip_path, sh_path))


def console(method, path, data=None):
    """One request to the console's developer mode (ALAV Store -> Settings)."""
    host = os.environ.get("ALAV_HOST")
    if not host:
        sys.exit("deploy needs developer mode on the console: ALAV Store -> Settings -> switch it on, then set "
                 "ALAV_HOST=<address shown there>. Without it use: python tool.py pack <slug>")
    id_file = os.path.expanduser("~/.alav-gamekit-device")  # this PC's id; the console remembers it once trusted
    if not os.path.isfile(id_file):
        with open(id_file, "w") as f:
            f.write(os.urandom(16).hex())
    with open(id_file) as f:
        headers = {"X-ALAV-Device": f.read().strip(), "X-ALAV-Name": re.sub(r"[^A-Za-z0-9 .-]", "", socket.gethostname())}
    if os.environ.get("ALAV_CODE"):  # optional: the code from Settings skips the question on the console
        headers["X-ALAV-Code"] = os.environ["ALAV_CODE"]
    url = "http://%s%s" % (host if ":" in host else host + ":3636", path)
    for attempt in range(40):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data, method=method, headers=headers),
                                        timeout=240) as response:
                return response.read()
        except urllib.error.HTTPError as e:
            if e.code != 401:
                sys.exit("console refused: " + e.read().decode("utf-8", "replace"))
            if attempt == 0:
                print("First time from this PC (id %s): open ALAV Store on the console and press A to trust "
                      "it (waiting up to 2 minutes)..." % headers["X-ALAV-Device"][:4], flush=True)
            time.sleep(2)
        except OSError as e:
            sys.exit("cannot reach the console at %s (is it on, on the same Wi-Fi, developer mode on?): %s" % (host, e))
    sys.exit("nobody confirmed this PC on the console. Ask the user to open ALAV Store and press A, then retry")


def cmd_deploy(args):
    if args[0] == "--stop":
        console("POST", "/stop")
        return 0
    flag = args[0] if args[0].startswith("--") else next((a for a in args[1:] if a.startswith("--")), "")
    slug = os.path.basename(game_dir(next(a for a in args if not a.startswith("--"))))
    app = "/apps/" + slug
    if flag == "--logs":
        print(console("GET", app + "/log").decode("utf-8", "replace"))
    elif flag == "--shot":
        os.makedirs(os.path.join(WORK, "out"), exist_ok=True)
        path = os.path.join(WORK, "out", slug + "-console.png")
        picture = console("GET", app + "/screenshot")
        with open(path, "wb") as f:
            f.write(picture)
        print("screenshot of the console screen: " + relpath(path, WORK))
    else:
        folder, _ = stage(slug)
        console("PUT", app, tar_bytes(folder))
        if flag == "--check":  # headless self-test on the real CPU; the screen is not touched
            print(console("POST", app + "/check").decode("utf-8", "replace"))
        else:
            console("POST", app + "/run" + ("?bot=1" if flag == "--bot" else ""))
            print("started on the console. Quit: SELECT+START. Log: python tool.py deploy %s --logs" % slug)
    return 0


