#!/usr/bin/env python3
"""ALAV Gamekit - one tool for everything.

AI agents: read AGENTS.md first. It has the rules and the whole API on one page;
you do not need to read kit/alav.py.

  python tool.py setup [folder]            once after cloning into a project: makes the project folder
                                           (default: the folder that contains this kit) a workspace -
                                           agent instructions in its root and its own games/ folder
  python tool.py new <slug> [--from <example>] [--title "My Game"]   create games/<slug>
  python tool.py run <slug> [--net]        play in a PC window (--net: two windows, host + join)
  python tool.py check <slug> [--net]      automatic test: prints PASS or FAIL with reasons
  python tool.py pack <slug>               build dist/ALAV-<slug>-<version>-linux-arm64.zip and dist/<Title>.sh
  python tool.py deploy <slug>             send to the console over Wi-Fi and start it
  python tool.py deploy <slug> --check     self-test on the console's CPU (screen not used)
  python tool.py deploy <slug> --bot       start it with random button presses
  python tool.py deploy <slug> --logs      the game's output on the console
  python tool.py deploy <slug> --shot      picture of the console screen -> out/<slug>-console.png
  python tool.py deploy --stop             stop the game
  python tool.py publish <slug>            upload to the ALAV Store as a draft that only you see
  python tool.py publish <slug> --release  ... and make it visible to everyone (or release that draft)

deploy needs developer mode: ALAV Store -> Settings on the console, then on the PC set
ALAV_HOST to the address shown there. The first time the console asks to trust this PC.
publish needs a developer key: register at https://alav.online/developers, create a key there and
set ALAV_KEY to it. The game needs icon.png (PNG, at most 128x128 px and 64 KiB). Optional fields in
game.json: "description", "genre", "kind" ("game" or "app"), "net" (true for network games).
<slug> is a folder name in games/ or examples/. After `setup`, games/, out/ and dist/ live in the
workspace folder, not inside the kit. Keys on a PC: arrows, X=A, Z=B, S=X, A=Y,
Q/W=L1/R1, Enter=START, Backspace=SELECT, Esc=quit.
"""
